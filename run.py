"""Run the whole pipeline. From this folder:

    python run.py validate   development only: December 2025 through March 2026
    python run.py collect-validation   combine saved dev + completed frozen confirmation
    python run.py report     score those predictions and draw a figure
    python run.py predict    predict the test homes and write the two submission files
    python run.py check      check the submission files before you hand them in
    python run.py compare    compare a rerun of predict with the committed reference files
    python run.py predict-saved   write the submission files from the saved trained models
                                  (no training; verify against the matching reference files)

On Windows, type py instead of python if python is not found.
"""
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

import data
import models
from check_submission import check_all

ROOT = Path(__file__).parent
TRACKS = ["off_market", "list_aware"]
# Walk-forward validation: each of these months is predicted by models trained only
# on the sales before that month, the same way the real test works.
VALIDATION_MONTHS = pd.period_range("2025-12", "2026-03", freq="M")


def validation_month_label(predictions):
    months = sorted(predictions["month"].astype(str).unique())
    return f"{months[0]} to {months[-1]}"


def _imported_confirmation(state, name, track, path):
    """Check per-home predictions from the imported lab confirmation (run once, before import).

    The lab run predates the source/data fingerprints, so the import record holds the SHA-256 of
    its metrics.json and spec.json instead. The predictions must sit next to those exact files and
    reproduce the recorded overall MdAPE and home count.
    """
    import confirmation
    for filename in ("metrics.json", "spec.json"):
        relative = path.with_name(filename).relative_to(ROOT).as_posix()
        if confirmation.sha256(path.with_name(filename)) != state["artifacts_sha256"].get(relative):
            raise ValueError(f"{relative} is not the imported lab confirmation file.")
    recorded = json.loads(path.with_name("metrics.json").read_text(encoding="utf-8"))[track]["overall"]
    frame = pd.read_csv(path)
    frame = frame[frame["track"] == track]
    error = 100 * (frame["predicted_price"] / frame["sold_price"] - 1).abs()
    if len(frame) != recorded["n"] or abs(float(error.median()) - recorded["mdape"]) > 0.001:
        raise ValueError(f"{path} does not reproduce the recorded confirmation metrics.")
    return json.loads(path.with_name("spec.json").read_text(encoding="utf-8")), frame


def collect_validation():
    """Assemble the official six months from saved predictions, without retraining."""
    import configs
    import confirmation
    record = ROOT / "outputs" / "final_confirmation.json"
    imported = (record.exists() and json.loads(record.read_text(encoding="utf-8")).get("origin")
                == "imported_lab_confirmation")
    if imported:
        # December-March must come from this source and data; April-May from the lab record.
        state = json.loads(record.read_text(encoding="utf-8"))
        current = json.loads(json.dumps(confirmation.snapshot(), default=str))
    else:
        state = confirmation.completed_campaign()
        current = state["freeze"]["snapshot"]
    frames = []
    for track, name in configs.FINAL.items():
        specs = {}
        for split, expected in (("dev", {str(m) for m in VALIDATION_MONTHS}),
                                ("confirm", {"2026-04", "2026-05"})):
            path = ROOT / "outputs" / "experiments" / name / split / "predictions.csv"
            if imported and split == "confirm":
                spec, frame = _imported_confirmation(state, name, track, path)
            else:
                spec = json.loads(path.with_name("spec.json").read_text(encoding="utf-8"))
                if (spec.get("source_sha256") != current["source_sha256"]
                        or spec.get("listings_sha256") != current["listings_sha256"]):
                    raise ValueError(f"Predictions were not generated by the frozen source/data: {path}")
                frame = pd.read_csv(path)
                frame = frame[frame["track"] == track]
            if set(frame["month"].astype(str)) != expected or frame["ml_num"].duplicated().any():
                raise ValueError(f"Unexpected months or repeated homes in {path}")
            specs[split] = spec
            frames.append(frame)
        if imported and json.dumps(specs["dev"].get("spec"), sort_keys=True, default=str) != \
                json.dumps(specs["confirm"].get("spec"), sort_keys=True, default=str):
            raise ValueError(f"{name}: development and confirmation used different model settings.")
    result = pd.concat(frames, ignore_index=True)
    if result.duplicated(["track", "ml_num"]).any():
        raise ValueError("Development and confirmation homes overlap.")
    path = ROOT / "outputs" / "validation_predictions.csv"
    path.parent.mkdir(exist_ok=True)
    result.to_csv(path, index=False)
    print(f"Wrote {path} ({validation_month_label(result)})")


def validate():
    listings = data.load("listings")
    results = []
    for month in VALIDATION_MONTHS:
        train = listings[listings["date_sold"] < month.start_time]
        homes = listings[listings["date_sold"].dt.to_period("M") == month]
        for track in TRACKS:
            model = models.make_model(track).fit(train)
            predicted = model.predict(data.hide_answers(homes, track))
            results.append(pd.DataFrame({
                "ml_num": homes["ml_num"], "track": track, "month": str(month),
                "house_type_name": homes["house_type_name"], "sold_price": homes["sold_price"],
                "predicted_price": np.round(predicted)}))
        print(f"{month}: trained on {len(train):,} earlier sales, predicted {len(homes):,} homes")
    path = ROOT / "outputs" / "validation_predictions.csv"
    path.parent.mkdir(exist_ok=True)
    pd.concat(results).to_csv(path, index=False)
    print(f"Wrote {path.relative_to(ROOT)}")


def bootstrap_ci(values, statistic, repeats=1000):
    """95% interval: recompute the statistic on 1,000 resamples of the homes
    (drawn with replacement) and keep the middle 95% of the results."""
    rng = np.random.default_rng(0)
    results = [statistic(rng.choice(values, size=len(values))) for _ in range(repeats)]
    return [round(float(x), 2) for x in np.percentile(results, [2.5, 97.5])]


def metrics(predictions):
    """Scores for one track. Errors are in percent of the sold price."""
    signed = 100 * (predictions["predicted_price"] - predictions["sold_price"]) / predictions["sold_price"]
    absolute = signed.abs().to_numpy()
    return {
        "n": len(predictions),
        "mape": round(float(np.mean(absolute)), 2),          # mean absolute % error
        "mape_95ci": bootstrap_ci(absolute, np.mean),
        "mdape": round(float(np.median(absolute)), 2),       # median absolute % error
        "mdape_95ci": bootstrap_ci(absolute, np.median),
        "median_signed_error": round(float(np.median(signed)), 2),  # above 0: predicts too high
    }


def report():
    path = ROOT / "outputs" / "validation_predictions.csv"
    if not path.exists():
        sys.exit(f"{path} does not exist yet: run `python run.py validate` first")
    predictions = pd.read_csv(path)
    scores = {track: metrics(predictions[predictions["track"] == track]) for track in TRACKS}

    (ROOT / "reports").mkdir(exist_ok=True)
    (ROOT / "reports" / "validation_report.json").write_text(json.dumps(scores, indent=2))
    lines = [
        "# Validation report", "",
        f"Walk-forward validation, {validation_month_label(predictions)}: each month was "
        "predicted by models trained only on the sales before it.",
        "Errors are (predicted - sold) / sold. Brackets: bootstrap 95% interval.", "",
        "| Track | Homes | MAPE | MdAPE | Median signed error |", "|---|---|---|---|---|"]
    for track, s in scores.items():
        lines.append(f"| {track} | {s['n']:,} | {s['mape']:.2f}% ({s['mape_95ci'][0]:.2f} to {s['mape_95ci'][1]:.2f}) "
                     f"| {s['mdape']:.2f}% ({s['mdape_95ci'][0]:.2f} to {s['mdape_95ci'][1]:.2f}) "
                     f"| {s['median_signed_error']:+.2f}% |")
    lines += [
        "", "MAPE: mean absolute percentage error. MdAPE: median absolute percentage error.",
        "A median signed error above 0 means the model tends to predict too high.",
        "The intervals treat homes as independent. Homes sold in the same month share the same",
        "market swings, so the real uncertainty is somewhat wider.", "",
        "![Error by price range](../figures/error_by_price_range.png)", ""]
    (ROOT / "reports" / "validation_report.md").write_text("\n".join(lines))
    write_latex_table(scores)
    error_by_price_range(predictions)
    print("\n".join(lines))
    print("Wrote reports/validation_report.md, reports/validation_report.json, reports/results_table.tex "
          "and figures/error_by_price_range.png")


def write_latex_table(scores):
    """The same scores as a LaTeX table, for report/report.tex to include."""
    rows = []
    for track, s in scores.items():
        name = track.replace("_", "-")
        rows.append(f"{name} & {s['n']:,} & {s['mdape']:.2f} ({s['mdape_95ci'][0]:.2f}--{s['mdape_95ci'][1]:.2f}) "
                    f"& {s['mape']:.2f} ({s['mape_95ci'][0]:.2f}--{s['mape_95ci'][1]:.2f}) "
                    f"& {s['median_signed_error']:+.2f} \\\\")
    table = "\n".join([
        "% Written by `python run.py report`. Do not edit by hand: rerun the command instead.",
        "\\begin{tabular}{lrccc}", "\\hline",
        "Track & Homes & MdAPE \\% (95\\% CI) & MAPE \\% (95\\% CI) & Median signed error \\% \\\\", "\\hline",
        *rows, "\\hline", "\\end{tabular}"])
    (ROOT / "reports" / "results_table.tex").write_text(table + "\n")


def error_by_price_range(predictions):
    """Figure: how big the errors are, from the cheapest tenth of homes to the dearest.

    Want more figures? Copy this function and group the errors by something else:
    house_type_name, month, or community (add it to the predictions file in validate()).
    """
    import matplotlib.pyplot as plt

    fig, ax = plt.subplots(figsize=(8, 4.5))
    colours = {"off_market": "#2a78d6", "list_aware": "#eb6834"}
    for track in TRACKS:
        rows = predictions[predictions["track"] == track]
        error = 100 * (rows["predicted_price"] - rows["sold_price"]).abs() / rows["sold_price"]
        decile = pd.qcut(rows["sold_price"], 10, labels=False) + 1   # 1 = cheapest tenth
        by_decile = error.groupby(decile)
        middle = by_decile.median()
        ax.plot(middle.index, middle.values, marker="o", linewidth=2, color=colours[track], label=track)
        ax.fill_between(middle.index, by_decile.quantile(0.25), by_decile.quantile(0.75),
                        color=colours[track], alpha=0.15, linewidth=0)
    prices = rows["sold_price"].groupby(decile).median()
    ax.set_xticks(prices.index, [f"{d}\n${p / 1e6:.2f}M" for d, p in prices.items()])
    ax.set_xlabel("Sold-price decile (1 = cheapest tenth of homes), with its median price")
    ax.set_ylabel("Absolute % error\n(line: median, band: middle 50%)")
    ax.set_title(f"Validation error by price range, {validation_month_label(predictions)}")
    ax.set_ylim(bottom=0)
    ax.grid(axis="y", color="#e5e5e5")
    ax.spines[["top", "right"]].set_visible(False)
    ax.legend(frameon=False)
    fig.tight_layout()
    (ROOT / "figures").mkdir(exist_ok=True)
    fig.savefig(ROOT / "figures" / "error_by_price_range.png", dpi=150)
    plt.close(fig)


def predict():
    """Fit the final models (configs.FINAL) on every listing and write both submission files.
    Also writes submissions/run_info.json: hardware, CatBoost device, versions and timings."""
    import os, platform, time
    started = time.time()
    listings = data.load("listings")
    (ROOT / "submissions").mkdir(exist_ok=True)
    info = {"final": dict(__import__("configs").FINAL), "machine": platform.node(),
            "processor": platform.processor(), "cpu_count": os.cpu_count(),
            "catboost_gpu_found": models.gpu_available(),
            "catboost_device_env": os.environ.get("SSU_CATBOOST_DEVICE", ""),
            "python": platform.python_version(), "versions": package_versions(), "tracks": {}}
    for track in TRACKS:
        t0 = time.time()
        homes = data.load(track)
        model = models.make_model(track).fit(listings)
        predicted = model.predict(homes)
        path = ROOT / "submissions" / f"submission_{track}.csv"
        pd.DataFrame({"ml_num": homes["ml_num"], "predicted_price": np.round(predicted)}).to_csv(path, index=False)
        save_model(model, track)
        devices = sorted({getattr(getattr(m, "learner", None), "catboost_device", None)
                          for m in getattr(model, "members", [model])} - {None})
        info["tracks"][track] = {"homes": len(homes), "seconds": round(time.time() - t0, 1),
                                 "catboost_device": devices}
        print(f"Wrote {path.relative_to(ROOT)} ({len(homes):,} homes) in {time.time() - t0:.0f}s"
              + (f", CatBoost on {devices[0]}" if devices else ""), flush=True)
    info["total_seconds"] = round(time.time() - started, 1)
    (ROOT / "submissions" / "run_info.json").write_text(json.dumps(info, indent=2))
    (model_dir() / "run_info.json").write_text(json.dumps(info, indent=2))
    print(f"Total {info['total_seconds'] / 60:.1f} min. Wrote submissions/run_info.json")


def model_dir():
    """Resolve saved models under ROOT at call time, including isolated tests."""
    return ROOT / "trained_models"


def save_model(model, track):
    """Keep the fitted model, so predictions can be redone without retraining (and so they
    can be compared with their matching CSVs; retraining on other hardware differs)."""
    import joblib
    model_dir().mkdir(exist_ok=True)
    joblib.dump(model, model_dir() / f"{track}.joblib", compress=3)


def predict_saved():
    """Write both submission files from the saved models in trained_models/ (no training).
    The saved models were trained on the hardware named in trained_models/run_info.json."""
    import joblib
    (ROOT / "submissions").mkdir(exist_ok=True)
    for track in TRACKS:
        homes = data.load(track)
        model = joblib.load(model_dir() / f"{track}.joblib")
        predicted = model.predict(homes)
        path = ROOT / "submissions" / f"submission_{track}.csv"
        pd.DataFrame({"ml_num": homes["ml_num"], "predicted_price": np.round(predicted)}).to_csv(path, index=False)
        print(f"Wrote {path.relative_to(ROOT)} ({len(homes):,} homes) from {model_dir().name}/{track}.joblib")


def package_versions():
    import importlib.metadata as md
    out = {}
    for name in ["pandas", "numpy", "scikit-learn", "scipy", "catboost", "lightgbm"]:
        try:
            out[name] = md.version(name)
        except Exception:
            pass
    return out


def compare():
    """Compare freshly written submissions/ with the committed reference files in
    submissions/reference/ (produced on the hardware named in submissions/reference/run_info.json)."""
    ref_dir = ROOT / "submissions" / "reference"
    ok = True
    for track in TRACKS:
        new = pd.read_csv(ROOT / "submissions" / f"submission_{track}.csv").set_index("ml_num")
        ref = pd.read_csv(ref_dir / f"submission_{track}.csv").set_index("ml_num")
        if set(new.index) != set(ref.index):
            print(f"{track}: the homes differ"); ok = False; continue
        diff = 100 * (new.loc[ref.index, "predicted_price"] - ref["predicted_price"]).abs() / ref["predicted_price"]
        same = (diff < 1e-9).mean() * 100
        print(f"{track}: {same:.1f}% identical; difference median {diff.median():.3f}%, "
              f"99th percentile {diff.quantile(0.99):.3f}%, max {diff.max():.3f}%")
    return ok


def check():
    return check_all(ROOT / "submissions")


COMMANDS = {"validate": validate, "report": report, "predict": predict, "check": check, "compare": compare,
            "predict-saved": predict_saved, "collect-validation": collect_validation}

if __name__ == "__main__":
    if len(sys.argv) != 2 or sys.argv[1] not in COMMANDS:
        sys.exit(__doc__)
    result = COMMANDS[sys.argv[1]]()
    sys.exit(1 if result is False else 0)
